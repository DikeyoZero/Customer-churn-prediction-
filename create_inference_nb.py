        "margin = z * np.sqrt(p_hat*(1-p_hat)/n + z**2/(4*n**2)) / denominator\n",
        "ci_lower = center - margin\n",
        "ci_upper = center + margin\n",
        "\n",
        "print(SEP)\n",
        "print('   KIEM DINH 3: CONFIDENCE INTERVAL')\n",
        "print('   Ty le Churn toan bo khach hang')\n",
