        "# ============================================================\n",
        "# KIỂM ĐỊNH 3: CONFIDENCE INTERVAL\n",
        "# ============================================================\n",
        "SEP = '=' * 55\n",
        "n = len(df)\n",
        "p_hat = df['Churn_binary'].mean()\n",
        "z = 1.96  # 95% CI\n",
        "\n",
        "# Wilson CI\n",
        "denominator = 1 + z**2/n\n",
